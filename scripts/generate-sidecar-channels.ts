/**
 * Writes `native/sidecar-client/channels.ts`: for every method of `window.workbench`
 * in `src/preload/index.ts`, the route channel it invokes. The native UI has no
 * preload, so its `workbench` object is built from this table.
 *
 * Run with `bun run native:channels` after changing the preload's surface; a test
 * fails while the table is out of date.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const repositoryRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const preloadPath = join(repositoryRoot, 'src', 'preload', 'index.ts')
const outputPath = join(repositoryRoot, 'native', 'sidecar-client', 'channels.ts')

/** The string a property name is written as, or null for a computed name. */
function propertyName(name: ts.PropertyName): string | null {
  if (ts.isIdentifier(name) || ts.isStringLiteral(name)) {
    return name.text
  }
  return null
}

/** The channel of the first `ipcRenderer.invoke('channel', …)` call inside the node, if there is one. */
function invokedChannel(node: ts.Node): string | null {
  let channel: string | null = null
  const visit = (child: ts.Node): void => {
    if (channel !== null) {
      return
    }
    if (ts.isCallExpression(child) && child.expression.getText() === 'ipcRenderer.invoke') {
      const first = child.arguments[0]
      if (first && ts.isStringLiteral(first)) {
        channel = first.text
        return
      }
    }
    ts.forEachChild(child, visit)
  }
  visit(node)
  return channel
}

/** Adds every method under `object` to `table`, keyed by its dotted path. */
function collectChannels(
  object: ts.ObjectLiteralExpression,
  path: string[],
  table: Record<string, string>
): void {
  for (const property of object.properties) {
    if (!ts.isPropertyAssignment(property)) {
      continue
    }
    const name = propertyName(property.name)
    if (name === null) {
      continue
    }
    if (ts.isObjectLiteralExpression(property.initializer)) {
      collectChannels(property.initializer, [...path, name], table)
      continue
    }
    const channel = invokedChannel(property.initializer)
    if (channel !== null) {
      table[[...path, name].join('.')] = channel
    }
  }
}

/** The channel table for the `workbench` object literal in the preload's source. */
export function extractChannels(preloadSource: string): Record<string, string> {
  const file = ts.createSourceFile('index.ts', preloadSource, ts.ScriptTarget.Latest, true)
  const table: Record<string, string> = {}
  file.forEachChild((statement) => {
    if (!ts.isVariableStatement(statement)) {
      return
    }
    for (const declaration of statement.declarationList.declarations) {
      const initializer = declaration.initializer
      if (declaration.name.getText() === 'workbench' && initializer && ts.isObjectLiteralExpression(initializer)) {
        collectChannels(initializer, [], table)
      }
    }
  })
  return table
}

/** The source of `channels.ts` for a table. */
export function renderChannels(table: Record<string, string>): string {
  const lines = Object.entries(table).map(([path, channel]) => `  '${path}': '${channel}',`)
  return [
    '// Generated by scripts/generate-sidecar-channels.ts from src/preload/index.ts; do not edit.',
    '// Every method of `window.workbench` that invokes a route, and the channel it invokes.',
    '',
    'export const workbenchChannels: Record<string, string> = {',
    ...lines,
    '}',
    ''
  ].join('\n')
}

if (import.meta.main) {
  const table = extractChannels(readFileSync(preloadPath, 'utf8'))
  writeFileSync(outputPath, renderChannels(table))
  console.log(`${Object.keys(table).length} channels written to ${outputPath}`)
}
